"""Backtest: score dumping hotspots as of one year ago, then check the year after.

The score uses only reports before the cutoff, so the 12 months after it are
data the ranking never saw. Prints how many top hotspots got dumped on again and
writes the full top-50 table to data/backtest/ so anyone can check it.

Run from the repo root after fetch_311.py and build_hotspots.py:
    python data/scripts/backtest.py
"""
import json

import numpy as np
import pandas as pd

from build_hotspots import CELL_LAT, CELL_LON, CLEAN, MIN_REPORTS, ROOT, meters

OUT = ROOT / "data" / "backtest"


def main():
    r = pd.read_json(CLEAN / "street_reports.json")
    r = r[r["type"] == "dumping"].copy()
    r["opened"] = pd.to_datetime(r["opened"])
    cut = r["opened"].max() - pd.Timedelta(days=365)
    r["cell"] = (r["lat"] // CELL_LAT).astype(int).astype(str) + "_" + (r["lon"] // CELL_LON).astype(int).astype(str)
    r["week"] = r["opened"].dt.to_period("W").astype(str)
    past, future = r[r["opened"] <= cut], r[r["opened"] > cut]
    after = future["cell"].value_counts()

    vac = np.array(json.loads((CLEAN / "vacant_buildings_lite.json").read_text()), dtype=object)
    vlat, vlon = vac[:, 1].astype(float), vac[:, 2].astype(float)

    rows = []
    for cell, g in past.groupby("cell"):
        if len(g) < MIN_REPORTS:
            continue
        in12 = g["opened"] > cut - pd.Timedelta(days=365)
        prev = (g["opened"] <= cut - pd.Timedelta(days=365)) & (g["opened"] > cut - pd.Timedelta(days=730))
        d = meters(g["lat"].mean(), g["lon"].mean(), vlat, vlon)
        rows.append({
            "cell": cell,
            "reports_12m": int(in12.sum()),
            "trend": (in12.sum() - prev.sum()) / max(prev.sum(), 1),
            "active_weeks_12m": g.loc[in12, "week"].nunique(),
            "vacant_within_150m": int((d <= 150).sum()),
            "address": g["address"].mode().iat[0] if g["address"].str.len().gt(0).any() else "",
        })
    h = pd.DataFrame(rows)
    # Same formula as build_hotspots.py; keep the two in sync.
    volume = h["reports_12m"].rank(pct=True)
    repeat = (h["active_weeks_12m"] / 52).clip(upper=1)
    trend = h["trend"].clip(-1, 1)
    vacant = (h["vacant_within_150m"] / 3).clip(upper=1)
    h["score"] = 100 * (0.4 * volume + 0.3 * repeat + 0.15 * (trend + 1) / 2 + 0.15 * vacant)
    h = h.sort_values(["score", "reports_12m"], ascending=False)
    h["after"] = h["cell"].map(after).fillna(0).astype(int)
    assert len(h) and h["after"].ge(0).all()

    summary = {
        "cutoff": f"{cut:%Y-%m-%d}",
        "hidden_window_end": f"{r['opened'].max():%Y-%m-%d}",
        "reports_after_cutoff": len(future),
        "hotspots_scored": len(h),
        "top": {
            n: {"dumped_on_again": int((h.head(n)["after"] > 0).sum()), "three_plus": int((h.head(n)["after"] >= 3).sum())}
            for n in (10, 25, 50, 100)
        },
    }
    top50 = [
        {"rank": i + 1, "cell": x.cell, "address": x.address, "score": round(float(x.score), 1),
         "reports_scored_year": x.reports_12m, "reports_hidden_year": int(x.after)}
        for i, x in enumerate(h.head(50).itertuples())
    ]
    OUT.mkdir(parents=True, exist_ok=True)
    (OUT / "results.json").write_text(json.dumps({"summary": summary, "top50": top50}) + "\n")
    lines = [
        "# Backtest results",
        "",
        f"Hotspots were scored using only 311 reports up to **{summary['cutoff']}**, with the same 0-100 formula as the app.",
        f"Then we counted dumping and debris reports in the next 12 months (to {summary['hidden_window_end']}), which the score never saw.",
        "",
        "| Top N | Got reports again | 3+ reports again |",
        "| --- | --- | --- |",
        *[f"| {n} | {v['dumped_on_again']} of {n} | {v['three_plus']} of {n} |" for n, v in summary["top"].items()],
        "",
        "Generated by `data/scripts/backtest.py`; the full list is in `results.json`.",
        "",
        "| Rank | Block (most common address) | Score | Reports, scored year | Reports, hidden year |",
        "| --- | --- | --- | --- | --- |",
        *[f"| {t['rank']} | {t['address']} | {t['score']} | {t['reports_scored_year']} | {t['reports_hidden_year']} |" for t in top50],
    ]
    (OUT / "RESULTS.md").write_text("\n".join(lines) + "\n")
    print(json.dumps(summary, indent=1))


if __name__ == "__main__":
    main()
